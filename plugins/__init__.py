"""libcore.plugins —— 插件子系统（总容器）。

一切可替换件都在这里，但**内部按维度分目录**，两个维度不是一个坐标系：

- ``capabilities/`` —— 能力插件（**节点**）：可被 Agent 点名的目标。
  走自发现加载器 + 配置=唯一真相源 + 热更新（无序，适合激进登记）。
- ``aspects/``      —— 横切面插件（**截面**）：拦截所有流经总线的信号。
  走显式装配（install_aspects），需控制顺序，不自动扫描、不热更。

约定：能力插件置于 ``capabilities/``，模块暴露 ``register(bus)``，
加载器负责"发现并登记"，让插件无需改任何调用方代码即可被 Agent 发现。
"""